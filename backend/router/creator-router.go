package router

import (
	"github.com/QuantumNous/new-api/controller"
	"github.com/QuantumNous/new-api/middleware"
	"github.com/gin-gonic/gin"
)

func registerCreatorRoutes(api *gin.RouterGroup) {
	public := api.Group("/creators", middleware.DisableCache())
	public.GET("/home", controller.PublicCreatorHome)
	public.GET("/home/posters/:id", controller.PublicCreatorHomePoster)
	public.GET("/people/:id", controller.PublicCreatorProfile)
	public.GET("/public", controller.PublicCreatorWorks)
	public.GET("/public/:id", controller.PublicCreatorWork)
	public.GET("/public/:id/cover", controller.PublicCreatorCover)
	public.GET("/files/:id", controller.CreatorDownload)
	public.HEAD("/files/:id", controller.CreatorDownload)
	me := public.Group("/me", middleware.UserAuth())
	me.GET("", controller.CreatorMe)
	me.GET("/access", controller.CreatorWatchAccess)
	me.GET("/home", controller.CreatorHomeMe)
	me.GET("/files/:id", controller.CreatorDownload)
	me.GET("/github", controller.CreatorGitHubStatus)
	me.GET("/github/repositories", controller.CreatorGitHubRepositories)
	me.Use(middleware.SessionCookieOriginGuard(), shopSameOrigin)
	me.POST("/github/start", middleware.UserCriticalRateLimit("CREATOR_GITHUB"), controller.CreatorGitHubStart)
	me.POST("/github/callback", middleware.UserCriticalRateLimit("CREATOR_GITHUB_CALLBACK"), controller.CreatorGitHubCallback)
	me.DELETE("/github", controller.CreatorGitHubDisconnect)
	me.POST("/github/import", middleware.UserCriticalRateLimit("CREATOR_GITHUB_IMPORT"), controller.CreatorGitHubImport)
	me.PUT("/home/cards/:id", controller.CreatorHomeSubmit)
	me.PUT("/home/cards/:id/display", controller.CreatorHomeDisplay)
	me.POST("/home/cards/:id/purchase", middleware.UserCriticalRateLimit("CREATOR_HOME_PURCHASE"), controller.CreatorHomePurchase)
	me.PUT("/home/avatar", controller.CreatorHomeAvatar)
	me.POST("/apply", middleware.UserCriticalRateLimit("CREATOR_APPLY"), controller.CreatorApply)
	me.PUT("/profile", controller.CreatorSaveProfile)
	me.PUT("/works/:id", controller.CreatorSaveWork)
	me.DELETE("/works/:id", controller.CreatorDeleteWork)
	me.PUT("/releases/:id", controller.CreatorSaveRelease)
	me.POST("/files", middleware.UserCriticalRateLimit("CREATOR_UPLOAD"), controller.CreatorUpload)
	me.DELETE("/files/:id", controller.CreatorDeleteFile)
	admin := public.Group("/admin", middleware.RootAuth())
	admin.GET("", controller.AdminCreatorCatalog)
	admin.GET("/showcase", controller.AdminCreatorShowcase)
	admin.PUT("/showcase", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorSaveShowcase)
	admin.PUT("/users/:id/status", middleware.SessionCookieOriginGuard(), shopSameOrigin, middleware.UserCriticalRateLimit("CREATOR_ADMIN_STATUS"), controller.AdminCreatorStatus)
	admin.POST("/users/:id/grant", middleware.SessionCookieOriginGuard(), shopSameOrigin, middleware.UserCriticalRateLimit("CREATOR_ADMIN_GRANT"), controller.AdminGrantCreator)
	admin.PUT("/review-policy", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorReviewPolicy)
	admin.GET("/files/:id", controller.CreatorDownload)
	admin.GET("/home", controller.AdminCreatorHome)
	admin.PUT("/home/showcase", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorHomeShowcase)
	admin.PUT("/home/config", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorHomeConfig)
	admin.PUT("/home/cards/:id", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorHomeReview)
	admin.PUT("/home/examples/:id", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorHomeExample)
	admin.PUT("/home/authors/:id", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorHomeAuthor)
	admin.POST("/:kind/:id", middleware.SessionCookieOriginGuard(), shopSameOrigin, controller.AdminCreatorReview)
}
